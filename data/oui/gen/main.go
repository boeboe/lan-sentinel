// Command gen downloads the IEEE MA-L, MA-M and MA-S registries and writes
// data/oui/oui.tsv.gz: one "PREFIX<TAB>Organisation" line per assignment
// (6, 7 or 9 hex digits), sorted, gzipped without a timestamp. Run it with
// `make oui`.
package main

import (
	"compress/gzip"
	"encoding/csv"
	"errors"
	"flag"
	"fmt"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"
)

var registries = []struct {
	name   string
	url    string
	digits int
}{
	{"MA-L", "https://standards-oui.ieee.org/oui/oui.csv", 6},
	{"MA-M", "https://standards-oui.ieee.org/oui28/mam.csv", 7},
	{"MA-S", "https://standards-oui.ieee.org/oui36/oui36.csv", 9},
}

func main() {
	out := flag.String("out", "data/oui/oui.tsv.gz", "output file")
	dir := flag.String("in", "", "read <MA-L|MA-M|MA-S>.csv from this directory instead of downloading")
	flag.Parse()
	if err := run(*out, *dir); err != nil {
		fmt.Fprintln(os.Stderr, "oui gen:", err)
		os.Exit(1)
	}
}

func run(out, dir string) error {
	entries := map[string]string{}
	for _, r := range registries {
		rc, err := open(r.name, r.url, dir)
		if err != nil {
			return err
		}
		n, err := parse(rc, r.digits, entries)
		_ = rc.Close()
		if err != nil {
			return fmt.Errorf("%s: %w", r.name, err)
		}
		fmt.Printf("%s: %d assignments\n", r.name, n)
	}
	keys := make([]string, 0, len(entries))
	for k := range entries {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	tmp := out + ".tmp"
	f, err := os.Create(tmp)
	if err != nil {
		return err
	}
	zw, err := gzip.NewWriterLevel(f, gzip.BestCompression)
	if err != nil {
		return err
	}
	fmt.Fprintf(zw, "# IEEE MA-L, MA-M and MA-S registries; %d assignments; generated by data/oui/gen\n", len(keys))
	for _, k := range keys {
		fmt.Fprintf(zw, "%s\t%s\n", k, entries[k])
	}
	if err := errors.Join(zw.Close(), f.Close()); err != nil {
		return err
	}
	fmt.Printf("wrote %s (%d assignments)\n", out, len(keys))
	return os.Rename(tmp, out)
}

func open(name, url, dir string) (io.ReadCloser, error) {
	if dir != "" {
		return os.Open(filepath.Join(dir, name+".csv"))
	}
	req, err := http.NewRequest(http.MethodGet, url, nil)
	if err != nil {
		return nil, err
	}
	req.Header.Set("User-Agent", "lan-sentinel-oui-generator")
	c := http.Client{Timeout: 2 * time.Minute}
	var lastErr error
	for attempt := 1; attempt <= 3; attempt++ {
		if attempt > 1 {
			time.Sleep(time.Duration(attempt*attempt) * time.Second)
		}
		resp, err := c.Do(req)
		if err != nil {
			lastErr = fmt.Errorf("download %s: %w", name, err)
			continue
		}
		if resp.StatusCode != http.StatusOK {
			_ = resp.Body.Close()
			lastErr = fmt.Errorf("download %s: %s", name, resp.Status)
			continue
		}
		return resp.Body, nil
	}
	return nil, lastErr
}

// parse reads an IEEE registry CSV (Registry, Assignment, Organization Name,
// Organization Address) into entries.
func parse(r io.Reader, digits int, entries map[string]string) (int, error) {
	cr := csv.NewReader(r)
	cr.FieldsPerRecord = -1
	cr.LazyQuotes = true
	header, err := cr.Read()
	if err != nil {
		return 0, err
	}
	if len(header) < 3 || !strings.EqualFold(strings.TrimSpace(header[1]), "Assignment") {
		return 0, fmt.Errorf("unexpected header %q", header)
	}
	n := 0
	for {
		rec, err := cr.Read()
		if errors.Is(err, io.EOF) {
			return n, nil
		}
		if err != nil {
			return n, err
		}
		if len(rec) < 3 {
			continue
		}
		prefix := strings.ToUpper(strings.TrimSpace(rec[1]))
		name := strings.TrimRight(strings.Join(strings.Fields(rec[2]), " "), ", ")
		if len(prefix) != digits || name == "" || strings.Trim(prefix, "0123456789ABCDEF") != "" {
			continue
		}
		entries[prefix] = name
		n++
	}
}
